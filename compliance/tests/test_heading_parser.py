class TestExtractSummary:
    def test_summary_has_expected_shape(self, contract: Contract) -> None:
        result = extract(SAMPLE_BLOB, contract)
        assert "objects" in result
        assert "summary" in result
        s = result["summary"]
        for key in (
            "objects_total",
            "objects_with_data",
            "properties_total",
            "properties_filled",
            "properties_capturable",
            "unfilled",
        ):
            assert key in s
        # 18 objects are extracted by the contract-driven parser: the contract
        # declares 19 destinations (20 schema entries minus 1 source), but
        # `oscal_control` carries handledByPrimaryParser=true, so it is filled
        # by fismatic and skipped here (D-9 / #43).
        primary_objs = [
            o for o in contract.destinations() if o.handled_by_primary_parser
        ]
        assert len(primary_objs) == 1  # oscal_control
        expected_objects = len(contract.destinations()) - len(primary_objs)
        assert s["objects_total"] == expected_objects
        assert s["objects_total"] == 18
        # At least the SSP, party, boundary, diagram, inheritance objects
        # should have data from the synthetic blob
        assert s["objects_with_data"] >= 5
        # Total properties = sum across all *non-primary* destination objects
        expected_total = sum(
            len(o.properties)
            for o in contract.destinations()
            if not o.handled_by_primary_parser
        )
        assert s["properties_total"] == expected_total
        # capturable excludes `derived` props and is <= total (D-12 / #47)
        assert s["properties_capturable"] <= s["properties_total"]
        # filled + unfilled should equal total
        assert s["properties_filled"] + len(s["unfilled"]) == s["properties_total"]


