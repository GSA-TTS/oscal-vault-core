class TestContractLoading:
    def test_loads_without_error(self, contract: Contract) -> None:
        assert contract.raw["kind"] == "DataContract"
        assert contract.raw["apiVersion"] == "v3.1.0"

    def test_destinations_excludes_source_object(self, contract: Contract) -> None:
        ids = {o.object_id for o in contract.destinations()}
        assert "fedramp_ssp_docx" not in ids  # source object excluded
        assert "oscal_ssp_system" in ids
        assert "oscal_party" in ids
        assert "oscal_x_diagram" in ids
        assert "oscal_control" in ids

    def test_source_object_marked(self, contract: Contract) -> None:
        assert "fedramp_ssp_docx" in contract.source_object_ids

    def test_objects_carry_oscal_metadata(self, contract: Contract) -> None:
        party = contract.objects_by_id["oscal_party"]
        assert party.oscal_type == "oscal.party"
        assert party.oscal_model == "party"
        assert party.destination_folder == "Organizations/"
        assert party.multiple is True

    def test_properties_carry_capture_strategy(self, contract: Contract) -> None:
        ssp = contract.objects_by_id["oscal_ssp_system"]
        title_prop = next(p for p in ssp.properties if p.name == "title")
        assert title_prop.capture_strategy == "heading_table_first"
        assert title_prop.source_heading == "Information System Name"
        assert title_prop.oscal_path == "system-security-plan.metadata.title"

    def test_relationships_loaded(self, contract: Contract) -> None:
        ssp = contract.objects_by_id["oscal_ssp_system"]
        assert len(ssp.relationships) == 3
        rel = ssp.relationships[0]
        assert rel["type"] == "foreignKey"
        assert rel["from"] == "oscal_ssp.system_owner_party_uuid"
        assert rel["to"] == "oscal_party.uuid"

    def test_validates_against_odcs_schema(self) -> None:
        try:
            import jsonschema
            from referencing import Registry, Resource
        except ImportError:
            pytest.skip("jsonschema + referencing not installed")
        schema = json.loads(_ODCS_SCHEMA.read_text(encoding="utf-8"))
        import yaml

        contract_data = yaml.safe_load(_CONTRACT.read_text(encoding="utf-8"))
        registry = Registry().with_resource(
            uri=str(_ODCS_SCHEMA.as_uri()),
            resource=Resource.from_contents(schema),
        )
        schema_id = schema.get("$id") or str(_ODCS_SCHEMA.as_uri())
        registry = registry.with_resource(
            uri=schema_id, resource=Resource.from_contents(schema)
        )
        validator = jsonschema.Draft201909Validator(schema, registry=registry)
        errors = list(validator.iter_errors(contract_data))
        assert errors == [], (
            f"Contract invalid against ODCS: {[e.message for e in errors]}"
        )


