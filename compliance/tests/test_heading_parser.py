class TestHeadingMatching:
    def test_exact_match_case_insensitive(self) -> None:
        assert _heading_matches("Information System Name", "Information System Name")
        assert _heading_matches("information system name", "Information System Name")
        assert _heading_matches(
            "Information   System   Name", "Information System Name"
        )

    def test_no_match_for_different_heading(self) -> None:
        assert not _heading_matches("Network Architecture", "Information System Name")

    def test_prefix_match_with_star(self) -> None:
        assert _heading_matches(
            "Systems Providing Controls to Example System",
            "Systems Providing Controls*",
        )
        assert not _heading_matches(
            "Systems Receiving Controls from Example System",
            "Systems Providing Controls*",
        )

    def test_regex_match(self) -> None:
        assert _heading_matches(
            "Systems Receiving Controls from Example System",
            "regex:^Systems Receiving Controls",
        )
        assert _heading_matches(
            "10.3\tSoftware Inventory",
            r"regex:^10\.3\s*Software Inventory",
        )
        assert not _heading_matches(
            "Systems Providing Controls",
            "regex:^Systems Receiving",
        )

    def test_section_number_prefix_stripped(self) -> None:
        # A numbered SSP heading must match the contract's unnumbered form,
        # since templates are inconsistent ("10.8 X" vs "X").
        assert _heading_matches(
            "10.8 DevOps/DevSecOps Management", "DevOps/DevSecOps Management"
        )
        assert _heading_matches(
            "10.9 Container-Based Workload Management",
            "Container-Based Workload Management",
        )
        assert _heading_matches("10 System Environment", "System Environment")
        assert _heading_matches("13.11 Physical", "Physical")
        # Unnumbered form still matches (regression guard).
        assert _heading_matches("System Environment", "System Environment")

    def test_section_number_strip_does_not_overmatch(self) -> None:
        # Stripping a number must not make unrelated headings collide.
        assert not _heading_matches(
            "10.8 DevOps/DevSecOps Management", "AWS Management"
        )
        # A bare number without a following title is not stripped into a match.
        assert not _heading_matches("10", "System Environment")


