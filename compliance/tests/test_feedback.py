class TestDocxSkeleton:
    def test_render_feedback_docx_produces_valid_docx(
        self, extract_result, contract, sections, tmp_path
    ) -> None:
        out = tmp_path / "sample.feedback.docx"
        stats = render_feedback_docx(
            extract_result, contract, sections, out, "sample.docx"
        )
        assert out.exists()
        assert out.stat().st_size > 0
        assert stats["output"] == str(out)
        assert stats["sections_total"] > 0

    def test_rendered_docx_is_openable_by_python_docx(
        self, extract_result, contract, sections, tmp_path
    ) -> None:
        from docx import Document

        out = tmp_path / "sample.feedback.docx"
        render_feedback_docx(extract_result, contract, sections, out, "sample.docx")
        # Should open without error
        doc = Document(str(out))
        # Should have headings (Title or Heading N styles)
        heading_texts = [
            p.text
            for p in doc.paragraphs
            if p.style
            and (p.style.name.startswith("Heading") or p.style.name == "Title")
        ]
        assert any("Feedback Skeleton" in h for h in heading_texts), (
            f"Expected 'Feedback Skeleton' in headings: {heading_texts!r}"
        )
        assert any("Skeleton TOC" in h for h in heading_texts), (
            f"Expected 'Skeleton TOC' in headings: {heading_texts!r}"
        )

    def test_template_is_reused(
        self, extract_result, contract, sections, tmp_path
    ) -> None:
        out1 = tmp_path / "out1.feedback.docx"
        template = tmp_path / "_feedback_template.docx"
        render_feedback_docx(
            extract_result,
            contract,
            sections,
            out1,
            "sample.docx",
            template_path=template,
        )
        assert template.exists()
        # Second render should reuse the template (no rebuild)
        out2 = tmp_path / "out2.feedback.docx"
        mtime_before = template.stat().st_mtime
        render_feedback_docx(
            extract_result,
            contract,
            sections,
            out2,
            "sample.docx",
            template_path=template,
        )
        mtime_after = template.stat().st_mtime
        assert mtime_before == mtime_after, "template should not be rebuilt"


