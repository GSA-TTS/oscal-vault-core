class TestMarkdownSkeleton:
    def test_skeleton_has_expected_sections(
        self, extract_result, contract, sections
    ) -> None:
        md = render_skeleton_markdown(extract_result, contract, sections, "sample.docx")
        assert "# Feedback Skeleton: sample.docx" in md
        assert "## Summary" in md
        assert "## TOC" in md
        assert "## Per-heading notes" in md
        assert "## Unfilled properties" in md

    def test_toc_lines_have_status_glyphs(
        self, extract_result, contract, sections
    ) -> None:
        md = render_skeleton_markdown(extract_result, contract, sections, "sample.docx")
        # Information System Name routes to oscal_ssp.title (filled) -> ✅
        assert "✅" in md
        # Systems Receiving Controls has routed but unfilled -> ❌
        assert "❌" in md
        # Some Unrouted Heading -> ⚠️
        assert "⚠️" in md

    def test_toc_includes_per_heading_fill_counts(
        self, extract_result, contract, sections
    ) -> None:
        md = render_skeleton_markdown(extract_result, contract, sections, "sample.docx")
        # Information System Name should show a fill ratio
        assert "Information System Name" in md
        # The line should contain "filled:" somewhere. Note: the catchall
        # dumper renders Heading 1 styles as H2 in markdown (H1 is reserved
        # for the doc title), so we match on H2 here.
        isn_line = next(
            line
            for line in md.splitlines()
            if "Information System Name" in line and "H2" in line
        )
        assert "filled:" in isn_line

    def test_unfilled_section_lists_property_and_source_heading(
        self, extract_result, contract, sections
    ) -> None:
        md = render_skeleton_markdown(extract_result, contract, sections, "sample.docx")
        # Systems Receiving Controls -> received_by unfilled
        # The per-heading notes section should mention the unfilled property
        # and its sourceHeading pattern
        assert "received_by" in md
        # The contract uses regex:^Systems Receiving Controls for received_by
        assert "regex:^Systems Receiving Controls" in md

    def test_unrouted_section_notes_original_content(
        self, extract_result, contract, sections
    ) -> None:
        md = render_skeleton_markdown(extract_result, contract, sections, "sample.docx")
        assert "Some Unrouted Heading With Content" in md
        assert "UNROUTED" in md
        # Should mention the original content counts
        assert "paragraph(s)" in md

    def test_generate_skeleton_writes_file(
        self, extract_result, contract, sections, tmp_path
    ) -> None:
        out = tmp_path / "sample.feedback.md"
        stats = generate_skeleton(
            extract_result, contract, sections, out, "sample.docx"
        )
        assert out.exists()
        assert stats["output"] == str(out)
        assert stats["sections_total"] > 0
        content = out.read_text(encoding="utf-8")
        assert "# Feedback Skeleton: sample.docx" in content


