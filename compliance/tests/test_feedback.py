class TestEndToEndRealSample:
    """If a catch-all dump of a real SSP is supplied (OSCAL_VAULT_SAMPLE_CATCHALL), run the full pipeline."""

    @pytest.fixture
    def real_sample_blob(self):
        path = Path(
            os.environ.get(
                "OSCAL_VAULT_SAMPLE_CATCHALL", "/nonexistent/sample.catchall.md"
            )
        )
        if not path.exists():
            pytest.skip(
                "OSCAL_VAULT_SAMPLE_CATCHALL not set to an existing catch-all dump"
            )
        return path

    def test_real_sample_skeleton(self, real_sample_blob, contract, tmp_path) -> None:
        md = real_sample_blob.read_text(encoding="utf-8")
        result = extract(md, contract)
        sections = parse_catchall_blob(md)
        out = tmp_path / "sample.feedback.md"
        generate_skeleton(result, contract, sections, out, str(real_sample_blob))
        assert out.exists()
        content = out.read_text(encoding="utf-8")
        # Real sample has Information System Name -> should be routed
        assert "Information System Name" in content
        # Real sample has Network Architecture -> should be routed
        assert "Network Architecture" in content
        # Real sample has Systems Receiving Controls (empty section) -> routed-empty
        assert "Systems Receiving Controls" in content
        # Skeleton should be reasonably compact (< 50KB for one SSP)
        assert len(content) < 50_000, (
            f"Skeleton too large ({len(content)} bytes) — should be compact"
        )

    def test_real_sample_docx(self, real_sample_blob, contract, tmp_path) -> None:
        md = real_sample_blob.read_text(encoding="utf-8")
        result = extract(md, contract)
        sections = parse_catchall_blob(md)
        out = tmp_path / "sample.feedback.docx"
        render_feedback_docx(result, contract, sections, out, str(real_sample_blob))
        assert out.exists()
        assert out.stat().st_size > 0
        # .docx should be reasonably compact (< 200KB for one SSP)
        assert out.stat().st_size < 200_000, (
            f"Feedback .docx too large ({out.stat().st_size} bytes)"
        )
