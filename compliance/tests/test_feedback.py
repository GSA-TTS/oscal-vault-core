class TestBuildFeedbackSections:
    def test_routed_section_has_destinations(self, feedback_sections) -> None:
        isn = next(
            (
                fb
                for fb in feedback_sections
                if fb.source_heading == "Information System Name"
            ),
            None,
        )
        assert isn is not None
        assert len(isn.destinations) >= 1
        # oscal_ssp.title routes here via heading_table_first
        dest_names = {(d.object_name, d.property_name) for d in isn.destinations}
        assert ("oscal_ssp", "title") in dest_names

    def test_unrouted_section_surfaced(self, feedback_sections) -> None:
        unrouted = next(
            (
                fb
                for fb in feedback_sections
                if fb.source_heading == "Some Unrouted Heading With Content"
            ),
            None,
        )
        assert unrouted is not None
        assert unrouted.destinations == []
        assert unrouted.original_paragraph_count >= 1

    def test_empty_section_not_surfaced(self, feedback_sections) -> None:
        # "Systems Receiving Controls from Sample System" is empty in the blob.
        # It IS routed (contract has a property for it), so it should appear
        # with destinations but 0 filled.
        receiving = next(
            (
                fb
                for fb in feedback_sections
                if fb.source_heading == "Systems Receiving Controls from Sample System"
            ),
            None,
        )
        assert receiving is not None
        # Routed (has destinations) but unfilled
        assert len(receiving.destinations) >= 1
        assert all(not d.is_filled for d in receiving.destinations)

    def test_dumper_structural_headings_excluded(self, feedback_sections) -> None:
        titles = {fb.source_heading for fb in feedback_sections}
        # The dumper's own structural sections should NOT appear
        assert "Catchall Dump: sample.docx" not in titles
        assert "Document Inventory" not in titles
        assert (
            "Body Content (in document order, grouped under each heading)" not in titles
        )

    def test_sections_in_document_order(self, feedback_sections) -> None:
        # Information System Name comes before General System Description
        # comes before Systems Receiving Controls
        titles = [fb.source_heading for fb in feedback_sections]
        idx_isn = titles.index("Information System Name")
        idx_gsd = titles.index("General System Description")
        idx_receiving = titles.index("Systems Receiving Controls from Sample System")
        assert idx_isn < idx_gsd < idx_receiving


