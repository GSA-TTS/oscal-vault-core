"""Local integrity evidence with explicit machine result and pending human sign-off."""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

STATUSES = ("PASS", "FAIL", "BLOCKED", "INCOMPLETE")


class StageError(RuntimeError):
    def __init__(self, status: str, reason: str):
        super().__init__(reason)
        self.status = status


def timestamp() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def overall_status(layers: dict) -> str:
    if set(layers) != {"L0", "L1", "L2", "L3"}:
        return "BLOCKED"
    statuses = [layer["status"] for layer in layers.values()]
    for status in ("FAIL", "INCOMPLETE", "BLOCKED"):
        if status in statuses:
            return status
    return (
        "PASS"
        if len(statuses) == 4 and all(s == "PASS" for s in statuses)
        else "BLOCKED"
    )


def write_report(output: Path, report: dict) -> None:
    report["status"] = overall_status(report["layers"])
    report["review_status"] = "PENDING"
    import jsonschema

    schema_path = (
        Path(__file__).resolve().parents[1]
        / "datacontracts/schemas/docx-integrity-v1.schema.json"
    )
    jsonschema.validate(
        report,
        json.loads(schema_path.read_text(encoding="utf-8")),
        format_checker=jsonschema.FormatChecker(),
    )
    write_json(output / "compare" / "final-report.json", report)
    write_markdown_report(output, report)


def write_markdown_report(output: Path, report: dict) -> None:
    lines = [
        "---",
        f"title: DOCX E2E Integrity Report — {report['system_id']}",
        "description: Local minimized machine evidence awaiting human review",
        "status: draft",
        "tier: 3",
        "---",
        "",
        f"# DOCX E2E Integrity Report — {report['system_id']}",
        "",
        "Generated by an AI-assisted integrity harness; not an authorization package.",
        f"- Machine status: **{report['status']}**",
        "- Human sign-off: **PENDING** (a machine PASS is not a fully reviewed document)",
        f"- Source SHA-256: `{report.get('source_sha256') or 'unavailable'}`",
        f"- Template family: `{report['template_family']}`",
        f"- Run timestamp: {report['timestamp']}",
        "",
        "## Integrity scorecard",
    ]
    lines += [
        f"- {name}: **{layer['status']}** — {layer.get('reason', '')}"
        for name, layer in report["layers"].items()
    ]
    lines += [
        "",
        "## Discrepancies and evidence",
        "See `final-report.json`, sibling comparison files and `../transcript.log`.",
        "Evidence uses hashes and locators by default; raw local IR and command output remain sensitive.",
        "",
        "## Human review decision",
        "- Decision: adopt / reference / decline / investigate",
        "- Reviewer:",
        "- Date:",
    ]
    (output / "compare" / "report.md").write_text(
        "\n".join(lines) + "\n", encoding="utf-8"
    )
