#!/usr/bin/env python3
"""Validate CUI classification + provenance sidecars against ADR-024's schema.

Walks ``examples/vault/*/classification/cui.yaml`` where present and
validates each against
``compliance/datacontracts/schemas/cui-provenance-v1.schema.json``. The
sidecar is **optional per-system** — a vault system with no sidecar is not
an error (see ADR-024's "Non-goals": this repo does not classify systems on
anyone's behalf, and most example systems have no real source document or
ISSO of record to classify against).

This script only checks the *shape* of a sidecar that exists. It has no
opinion on whether a given `cui_category` or `authority` is factually
correct for a real system — that determination belongs to the data owner
and ISSO, never to this validator.

Usage:
    python3 compliance/scripts/validate_cui_contracts.py
    python3 compliance/scripts/validate_cui_contracts.py --vault examples/vault/<system>
    python3 compliance/scripts/validate_cui_contracts.py --coverage
    python3 compliance/scripts/validate_cui_contracts.py --coverage --out docs/analyses/45-cui-sidecar-coverage.md

Exit code is non-zero only if a *present* sidecar fails schema validation.
Missing sidecars are informational (see --coverage).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, List, Tuple

import yaml

try:
    import jsonschema
except ImportError:  # pragma: no cover - dev dependency, see pyproject.toml
    jsonschema = None

_CORE_ROOT = Path(__file__).resolve().parents[2]
_WORKSPACE = Path.cwd()
_SCHEMA_PATH = (
    _CORE_ROOT
    / "compliance"
    / "datacontracts"
    / "schemas"
    / "cui-provenance-v1.schema.json"
)
_EXAMPLES_DIR = _WORKSPACE / "examples" / "vault"


def _resolve_vaults(arg_vaults: List[str] | None) -> List[Path]:
    if arg_vaults:
        return [Path(v).resolve() for v in arg_vaults]
    if _EXAMPLES_DIR.is_dir():
        return [
            d
            for d in sorted(_EXAMPLES_DIR.iterdir())
            if d.is_dir() and not d.name.startswith(".")
        ]
    return []


def _load_schema() -> dict[str, Any]:
    import json

    with _SCHEMA_PATH.open(encoding="utf-8") as f:
        return json.load(f)


def _find_sidecar(vault: Path) -> Path | None:
    p = vault / "classification" / "cui.yaml"
    return p if p.exists() else None


def validate_sidecar(path: Path, schema: dict[str, Any]) -> List[str]:
    """Return a list of schema-violation messages (empty if valid)."""
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        return [f"YAML parse error: {exc}"]

    if jsonschema is None:
        return [
            "jsonschema not installed — run "
            "`uv run --with jsonschema --with pyyaml python "
            "scripts/validate_cui_contracts.py`"
        ]

    validator = jsonschema.Draft201909Validator(schema)
    errors = sorted(validator.iter_errors(data), key=lambda e: list(e.path))
    return [
        f"{'/'.join(str(p) for p in e.path) or '<root>'}: {e.message}" for e in errors
    ]


def _has_parsing_contract(vault: Path) -> bool:
    """A system is a candidate for classification once it has a
    Controls/ directory (i.e. real extracted content exists to classify).
    """
    return (vault / "Controls").is_dir() and any((vault / "Controls").glob("*.md"))


def build_coverage(vaults: List[Path]) -> Tuple[List[dict[str, Any]], int, int]:
    rows: List[dict[str, Any]] = []
    with_sidecar = 0
    candidates = 0
    for v in vaults:
        sidecar = _find_sidecar(v)
        is_candidate = _has_parsing_contract(v)
        if is_candidate:
            candidates += 1
        if sidecar:
            with_sidecar += 1
        rows.append(
            {
                "system": v.name,
                "candidate": is_candidate,
                "has_sidecar": sidecar is not None,
            }
        )
    return rows, with_sidecar, candidates


def render_coverage_markdown(
    rows: List[dict[str, Any]], with_sidecar: int, candidates: int
) -> str:
    lines = [
        "# CUI Sidecar Coverage",
        "",
        "Generated by `scripts/validate_cui_contracts.py --coverage`. See",
        "[ADR-024](../ADR/ADR-024-cui-provenance-datacontract.md) — a",
        "sidecar is optional per-system; this report is informational, not",
        "a compliance gate.",
        "",
        f"- Candidate systems (have a `Controls/` directory): **{candidates}**",
        f"- Systems with a `classification/cui.yaml` sidecar: **{with_sidecar}**",
        "",
        "| System | Candidate | Has sidecar |",
        "| --- | --- | --- |",
    ]
    for row in rows:
        lines.append(
            f"| {row['system']} | {'yes' if row['candidate'] else 'no'} | "
            f"{'yes' if row['has_sidecar'] else 'no'} |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Validate CUI classification/provenance sidecars (ADR-024)."
    )
    parser.add_argument(
        "--vault",
        action="append",
        default=None,
        help="Vault directory (repeatable; default: every vault in examples/vault/)",
    )
    parser.add_argument(
        "--coverage",
        action="store_true",
        help="Report sidecar coverage across vault systems instead of validating.",
    )
    parser.add_argument(
        "--out",
        type=str,
        default=None,
        help="Write the --coverage report to this path (default: stdout).",
    )
    args = parser.parse_args(argv)

    vaults = _resolve_vaults(args.vault)
    if not vaults:
        print("No vault directories found. Use --vault.", file=sys.stderr)
        return 0

    if args.coverage:
        rows, with_sidecar, candidates = build_coverage(vaults)
        report = render_coverage_markdown(rows, with_sidecar, candidates)
        if args.out:
            out_path = Path(args.out)
            out_path.parent.mkdir(parents=True, exist_ok=True)
            out_path.write_text(report, encoding="utf-8")
            print(f"Wrote coverage report to {out_path}")
        else:
            print(report)
        return 0

    schema = _load_schema()
    failures = 0
    checked = 0
    for v in vaults:
        sidecar = _find_sidecar(v)
        if not sidecar:
            continue
        checked += 1
        issues = validate_sidecar(sidecar, schema)
        try:
            display = sidecar.relative_to(_WORKSPACE)
        except ValueError:
            display = sidecar
        if issues:
            failures += 1
            print(f"[FAIL] {display}")
            for issue in issues:
                print(f"        {issue}")
        else:
            print(f"[PASS] {display}")

    print()
    if checked == 0:
        print("OK: no CUI sidecars present (schema is optional per-system).")
        return 0
    if failures:
        print(f"FAILED: {failures}/{checked} sidecar(s) failed schema validation.")
        return 1
    print(f"OK: {checked} sidecar(s) valid.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
